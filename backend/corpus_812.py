"""Canonical 2D corpus formation projection and learning-coverage helpers.

Source of truth:
CVLN_Academy_Cartographie_2D_Master.xlsx / Master_Catalogue!A1:H813.

The workbook stays authoritative. This module stores only the derived formation-code
projection required to reconcile the 812-row corpus with runtime learning objects.
It deliberately distinguishes module structure from authored learning content: the
LX v2 autogenerated fallback is not counted as real pedagogical content.
"""

